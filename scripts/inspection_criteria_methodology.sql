-- ---------- 4) تحديث الأوزان الكلية للمجالات ----------
UPDATE osh_inspection_domains d
SET total_weight = COALESCE((
  SELECT SUM(weight) FROM inspection_criteria c
  WHERE c.domain = d.domain_code AND c.is_active = TRUE
), 0);

-- ---------- 5) ملخص المنهجية ----------
SELECT
  (SELECT COUNT(*) FROM osh_inspection_domains WHERE is_active = TRUE) AS domains_count,
  (SELECT COUNT(*) FROM inspection_criteria WHERE criterion_code LIKE 'OSH-%' AND is_active = TRUE) AS criteria_count,
  (SELECT SUM(weight) FROM inspection_criteria WHERE criterion_code LIKE 'OSH-%' AND is_active = TRUE) AS total_weight;