-- inspection_criteria_methodology.sql — منهجية معايير التفتيش المعيارية
-- إطار تقييم موحد ودقيق للسلامة والصحة المهنية (OSH) وفق:
--   • قانون العمل اليمني رقم 5 لسنة 1995 (الفصل التاسع: السلامة المهنية)
--   • إطار عمل ILO-OSH 2001 (المبادئ التوجيهية لأنظمة السلامة والصحة)
--   • ISO 45001:2018 (نظام إدارة السلامة والصحة المهنية)
--
-- منهجية التقييم:
--   كل معيار له: رمز فريد (OSH-XX-NN) | مجال | وزن نسبي | طريقة قياس |
--   درجة خطورة الحد الأدنى | السند القانوني | إجراء التصحيح
--   درجة الامتثال للمنشأة = Σ(وزن × نسبة تحقق المعيار) / Σ(الأوزان) × 100
-- ============================================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ---------- 1) ضمان أعمدة المنهجية على جدول المعايير ----------
ALTER TABLE inspection_criteria ADD COLUMN IF NOT EXISTS criterion_code TEXT;
ALTER TABLE inspection_criteria ADD COLUMN IF NOT EXISTS domain TEXT;
ALTER TABLE inspection_criteria ADD COLUMN IF NOT EXISTS weight NUMERIC(5,2) DEFAULT 1.00;
ALTER TABLE inspection_criteria ADD COLUMN IF NOT EXISTS measurement_method TEXT;
ALTER TABLE inspection_criteria ADD COLUMN IF NOT EXISTS min_severity TEXT DEFAULT 'minor'
  CHECK (min_severity IN ('minor','major','critical'));
ALTER TABLE inspection_criteria ADD COLUMN IF NOT EXISTS legal_reference TEXT;
ALTER TABLE inspection_criteria ADD COLUMN IF NOT EXISTS corrective_action TEXT;
ALTER TABLE inspection_criteria ADD COLUMN IF NOT EXISTS standard_ref TEXT;
ALTER TABLE inspection_criteria ADD COLUMN IF NOT EXISTS is_active BOOLEAN DEFAULT TRUE;

CREATE UNIQUE INDEX IF NOT EXISTS uq_inspection_criteria_code
  ON inspection_criteria(criterion_code) WHERE criterion_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_inspection_criteria_domain
  ON inspection_criteria(domain) WHERE is_active = TRUE;

