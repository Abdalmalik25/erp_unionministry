-- ---------- 1) إصلاح فجوة المحافظات: إضافة محافظة المحويت ----------
INSERT INTO governorates (code, name_ar, name_en, region, is_active)
SELECT 'MhW', 'المحويت', 'Al Mahwit', 'الغربية', true
WHERE NOT EXISTS (SELECT 1 FROM governorates WHERE name_ar = 'المحويت');

-- ---------- 2) الأنشطة الوطنية (65) — مشتقة من ISIC-4 ----------
INSERT INTO national_activities (code, parent_code, name_ar, sector, level, status, version)
SELECT
    i.isic_code,
    NULLIF(i.parent_code, ''),
    i.description_ar,
    i.sector,
    i.level,
    'active',
    1
FROM isic4_classifications i
WHERE NOT EXISTS (SELECT 1 FROM national_activities na WHERE na.code = i.isic_code)
ON CONFLICT (code) DO UPDATE SET
    name_ar = EXCLUDED.name_ar,
    sector  = EXCLUDED.sector,
    level   = EXCLUDED.level,
    status  = 'active';

